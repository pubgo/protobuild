package protobuild

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"

	"github.com/pubgo/funk/v2/pathutil"
	"github.com/pubgo/funk/v2/recovery"
	"github.com/pubgo/redant"
	"gopkg.in/yaml.v3"

	"github.com/pubgo/protobuild/internal/typex"
)

// bufCfg is the generated buf workspace config file name.
var bufCfg = "buf.yaml"

// bufModule mirrors a single module entry in buf.yaml v2.
type bufModule struct {
	Path string `yaml:"path"`
}

// bufConfig mirrors the subset of buf.yaml v2 used by protobuild.
type bufConfig struct {
	Version string      `yaml:"version"`
	Modules []bufModule `yaml:"modules"`
}

const bufConfigHeader = `# Generated by 'protobuild buf'. DO NOT EDIT.
# buf CLI / buf lsp 只识别 buf 配置，不识别 protobuf.yaml。
# 这里把 protobuf.yaml 的 root 和 vendor 目录声明为 buf module root，
# 使 buf 的 import 解析与 protobuild (includes: root + vendor) 保持一致。
`

// newBufCommand creates the buf command.
// buf CLI / buf lsp resolves imports relative to buf module roots (buf.yaml),
// without buf.yaml the project root becomes the only module root and imports
// like "retag/retag.proto" (vendored under .proto/retag) can not be resolved.
func newBufCommand(force *bool) *redant.Command {
	return &redant.Command{
		Use:   "buf",
		Short: "生成 buf.yaml，供 buf CLI / buf lsp 解析 proto import 使用",
		Options: typex.Options{
			redant.Option{
				Flag:        "force",
				Shorthand:   "f",
				Description: "覆盖已存在的 buf.yaml",
				Value:       redant.BoolOf(force),
			},
		},
		Middleware: withParseConfig(),
		Handler: func(ctx context.Context, inv *redant.Invocation) error {
			defer recovery.Exit()

			path, err := writeBufConfig(*force)
			if err != nil {
				return err
			}

			if path == "" {
				fmt.Printf("✅ %s is up to date\n", bufCfg)
				return nil
			}

			fmt.Printf("✅ Generated %s\n", path)
			for _, m := range globalCfg.Root {
				fmt.Printf("   module: %s\n", m)
			}
			fmt.Printf("   module: %s (vendor)\n", globalCfg.Vendor)
			fmt.Println("💡 提示: buf lsp 已启动时需要重启才能加载新的 buf.yaml")
			return nil
		},
	}
}

// writeBufConfig generates buf.yaml from the protobuild config.
// It returns the written file path, or an empty string if the file is up to date.
func writeBufConfig(force bool) (string, error) {
	var modules []bufModule
	seen := make(map[string]bool)

	// root dirs and the vendor dir are buf module roots, the same dirs that
	// protobuild passes to protoc as import paths.
	paths := append(globalCfg.Root, globalCfg.Vendor)
	for _, p := range paths {
		p = filepath.Clean(p)
		if p == "." || seen[p] {
			continue
		}

		if !pathutil.IsExist(p) {
			fmt.Printf("⚠️  跳过不存在的目录: %s\n", p)
			continue
		}

		seen[p] = true
		modules = append(modules, bufModule{Path: p})
	}

	if len(modules) == 0 {
		return "", errors.New("no proto root or vendor directories found, nothing to generate")
	}

	cfg := bufConfig{Version: "v2", Modules: modules}

	var out bytes.Buffer
	out.WriteString(bufConfigHeader)
	enc := yaml.NewEncoder(&out)
	enc.SetIndent(2)
	if err := enc.Encode(&cfg); err != nil {
		return "", err
	}
	if err := enc.Close(); err != nil {
		return "", err
	}

	path := filepath.Join(pwd, bufCfg)
	if old, err := os.ReadFile(path); err == nil {
		if bytes.Equal(old, out.Bytes()) {
			return "", nil
		}

		if !force {
			return "", fmt.Errorf("%s already exists with different content (use --force to overwrite)", path)
		}
	} else if !errors.Is(err, fs.ErrNotExist) {
		return "", err
	}

	if err := os.WriteFile(path, out.Bytes(), 0o644); err != nil {
		return "", err
	}

	return path, nil
}
