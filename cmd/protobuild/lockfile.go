package protobuild

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/pubgo/funk/v2/pathutil"
	"github.com/pubgo/protobuild/internal/shutil"
	"gopkg.in/yaml.v3"

	"github.com/pubgo/protobuild/internal/config"
	"github.com/pubgo/protobuild/internal/depresolver"
)

// lockfileName is written to the project root and should be committed:
// it records what was actually resolved, independent of user-edited config.
const lockfileName = "protobuf.lock.yaml"

// lockDep records the resolved state of a single dependency.
type lockDep struct {
	Name string `yaml:"name"`
	URL  string `yaml:"url,omitempty"`
	Path string `yaml:"path,omitempty"`
	// Version is the version recorded in config at vendor time.
	Version string `yaml:"version,omitempty"`
	// Commit is the resolved git commit of the cached checkout, captured
	// best-effort so floating refs (main, master) stay reproducible.
	Commit string `yaml:"commit,omitempty"`
}

// lockfile pins the resolved dependency state across vendor runs.
type lockfile struct {
	Version     int        `yaml:"version"`
	GeneratedAt time.Time  `yaml:"generated_at"`
	Deps        []*lockDep `yaml:"deps"`
}

// buildLockfile snapshots the current config deps. localPaths maps dep names
// to their resolved cache checkout, used to capture the git commit.
func buildLockfile(cfg *config.Config, localPaths map[string]string) *lockfile {
	l := &lockfile{Version: 1, GeneratedAt: time.Now().UTC()}

	for _, dep := range cfg.Depends {
		if dep.Name == "" || dep.Url == "" {
			continue
		}

		ld := &lockDep{
			Name: dep.Name,
			URL:  dep.Url,
			Path: dep.Path,
		}
		if dep.Version != nil {
			ld.Version = *dep.Version
		}

		if depresolver.DetectSource(dep.Url) == depresolver.SourceGit {
			if localPath := localPaths[dep.Name]; localPath != "" && pathutil.IsExist(localPath) {
				ld.Commit = gitHeadCommit(localPath)
			}
		}

		l.Deps = append(l.Deps, ld)
	}

	return l
}

// gitHeadCommit returns the HEAD commit of a git checkout, best-effort.
func gitHeadCommit(dir string) string {
	out, err := os.ReadFile(filepath.Join(dir, ".git", "HEAD")) // fast path
	if err == nil {
		if ref := strings.TrimSpace(string(out)); !strings.HasPrefix(ref, "ref:") {
			return ref
		}
	}

	// fall back to git (worktrees, packed refs, shallow clones)
	if out, err := shutil.Run("git", "-C", dir, "rev-parse", "HEAD"); err == nil {
		return strings.TrimSpace(out)
	}
	return ""
}

// saveLockfile writes the lockfile to the project root.
func saveLockfile(l *lockfile) error {
	data, err := yaml.Marshal(l)
	if err != nil {
		return err
	}
	header := []byte("# Generated by 'protobuild vendor'. Commit this file for reproducible vendor.\n")
	return os.WriteFile(filepath.Join(pwd, lockfileName), append(header, data...), 0o644)
}

// loadLockfile reads the lockfile, returning nil when it does not exist.
func loadLockfile() (*lockfile, error) {
	path := filepath.Join(pwd, lockfileName)
	if !pathutil.IsExist(path) {
		return nil, nil
	}

	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}

	var l lockfile
	if err := yaml.Unmarshal(data, &l); err != nil {
		return nil, fmt.Errorf("解析 %s 失败: %w", lockfileName, err)
	}
	return &l, nil
}

// diffDeps compares the lockfile against the current config and returns
// human-readable drift descriptions (name/version changes).
func (l *lockfile) diffDeps(cfg *config.Config) []string {
	if l == nil {
		return nil
	}

	locked := make(map[string]*lockDep, len(l.Deps))
	for _, d := range l.Deps {
		locked[d.Name] = d
	}

	var drift []string
	for _, dep := range cfg.Depends {
		if dep.Name == "" || dep.Url == "" {
			continue
		}

		old, ok := locked[dep.Name]
		if !ok {
			drift = append(drift, fmt.Sprintf("%s: lockfile 中不存在（新增依赖）", dep.Name))
			continue
		}

		current := ""
		if dep.Version != nil {
			current = *dep.Version
		}
		if old.Version != current {
			drift = append(drift, fmt.Sprintf("%s: %s -> %s", dep.Name, old.Version, current))
		}
		if old.URL != dep.Url {
			drift = append(drift, fmt.Sprintf("%s: URL 变更 %s -> %s", dep.Name, old.URL, dep.Url))
		}
	}
	return drift
}
